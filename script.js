// ================================
// LANGUAGE FUNCTION
// ================================

function setLanguage(language) {

    const selectedTranslations = translations[language];

    document.querySelectorAll("[data-i18n]").forEach(element => {

        const key = element.dataset.i18n;

        if (selectedTranslations[key]) {
            element.textContent = selectedTranslations[key];
        }

    });


    // Change page title
    document.title = selectedTranslations.pageTitle;


    // Change meta description
    const metaDescription =
        document.querySelector('meta[name="description"]');

    if (metaDescription) {
        metaDescription.setAttribute(
            "content",
            selectedTranslations.metaDescription
        );
    }


    // Change HTML language attribute
    document.documentElement.lang = language;

    //Switch CV depending on language
    const cvButton = document.getElementById("cv-download");

    if (cvButton) {
        if (language === "de") {
            cvButton.href = "assets/cv/cv-de.pdf";
            cvButton.download = "cv-de.pdf";
        } else {
            cvButton.href = "assets/cv/cv-en.pdf";
            cvButton.download = "cv-en.pdf";
        }
    }


    // Update active language button
    document
        .querySelectorAll(".language-button")
        .forEach(button => {

            button.classList.toggle(
                "active",
                button.dataset.lang === language
            );

        });


    // Remember selected language
    localStorage.setItem(
        "portfolioLanguage",
        language
    );

}


// ================================
// LANGUAGE BUTTONS
// ================================

document
    .querySelectorAll(".language-button")
    .forEach(button => {

        button.addEventListener("click", () => {

            setLanguage(
                button.dataset.lang
            );

        });

    });


// ================================
// LOAD SAVED LANGUAGE
// ================================

const savedLanguage =
    localStorage.getItem("portfolioLanguage");

if (
    savedLanguage === "en" ||
    savedLanguage === "de"
) {

    setLanguage(savedLanguage);

} else {

    setLanguage("en");

}


